<h1>Política de privacidad</h1>
<p class="f">Botacura Cajón del Maipo · Última actualización: 22 de octubre de 2026</p>

<p>Esta política explica qué datos personales tratamos cuando reservas, compras una Gift Card o nos escribes por WhatsApp, Instagram o correo, y cómo puedes ejercer tus derechos. El responsable es Centro Recreativo Botacura Ltda., Camino al Volcán 13274, El Manzano, km 27, San José de Maipo, Región Metropolitana, Chile. Contacto: <a href="mailto:botacura.info@gmail.com">botacura.info@gmail.com</a> · WhatsApp +56 9 7448 4112.</p>

<h2>1. Qué datos tratamos</h2>
<ul>
<li>Datos de contacto y reserva: nombre, teléfono, correo electrónico, fecha, cantidad de personas, programa y servicios elegidos, preferencias de menú y alergias alimentarias que nos informes.</li>
<li>Datos de pago: comprobantes de transferencia y datos de facturación. No almacenamos números de tarjeta; los pagos en línea los procesa el proveedor de pagos.</li>
<li>Mensajes: el contenido de las conversaciones por WhatsApp (texto, imágenes, audios y documentos que nos envíes), con su fecha y número de teléfono.</li>
</ul>

<h2>2. Para qué los usamos</h2>
<ul>
<li>Responder consultas sobre disponibilidad, precios y programas.</li>
<li>Crear, confirmar, modificar y gestionar tus reservas y Gift Cards.</li>
<li>Enviarte confirmaciones, recordatorios e información de tu visita.</li>
<li>Emitir documentos tributarios y cumplir obligaciones legales.</li>
</ul>
<p>No vendemos ni cedemos tus datos a terceros para publicidad.</p>

<h2>3. WhatsApp y asistente de reservas</h2>
<p>Nuestro número de WhatsApp está conectado a nuestra propia plataforma de reservas mediante la API de WhatsApp Business de Meta. Un asistente automático puede responder tus mensajes; los audios se transcriben a texto para poder entenderlos. Las conversaciones solo se usan para atenderte y gestionar tu reserva. Siempre puedes pedir hablar con una persona del equipo.</p>

<h2>4. Con quién se comparten</h2>
<p>Solo con proveedores que nos prestan servicios necesarios y que tratan los datos por encargo nuestro: Meta (WhatsApp e Instagram), alojamiento de servidores, correo electrónico, procesamiento de pagos y servicios de inteligencia artificial usados para responder y transcribir mensajes. También podemos entregarlos cuando la ley o una autoridad competente lo exija.</p>

<h2>5. Cuánto tiempo los guardamos</h2>
<p>Los datos de reservas y conversaciones se guardan mientras sean necesarios para prestar el servicio y atender reclamos, y hasta 24 meses después de tu última visita o mensaje. Los documentos tributarios se conservan por los plazos que exige la ley chilena.</p>

<h2>6. Tus derechos y eliminación de datos</h2>
<p>Puedes pedir acceso, rectificación, eliminación u oposición al tratamiento de tus datos (Ley N° 19.628 sobre protección de la vida privada). Para pedir que eliminemos tus datos, escribe a <a href="mailto:botacura.info@gmail.com">botacura.info@gmail.com</a> o por WhatsApp al +56 9 7448 4112 indicando tu nombre y número de teléfono. Responderemos dentro de 15 días hábiles y eliminaremos tus datos, salvo los que debamos conservar por obligación legal.</p>

<h2>7. Seguridad</h2>
<p>Usamos conexiones cifradas, acceso restringido por usuario y contraseña y respaldos para proteger la información.</p>

<h2>8. Cambios</h2>
<p>Si cambiamos esta política, publicaremos la nueva versión en esta misma página con su fecha de actualización.</p>

